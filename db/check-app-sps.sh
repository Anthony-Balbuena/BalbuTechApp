if [ "$mal_mapeo" -gt 0 ]; then
  echo "Mapeo rutina->permiso: $mal_mapeo rutina(s) con el permiso equivocado." >&2
  echo "  Corre: mariadb ... --database=$DB_NAME < db/mapear-permisos.sql" >&2
  exit 1
fi
echo "Mapeo rutina->permiso: $checkeadas rutinas verificadas."
exit 0
