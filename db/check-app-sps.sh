SP_CONTAR_INVENTARIO|CONSULTAR_PRODUCTOS
SP_REPORTE_STOCK_CRITICO_PAGINADO|CONSULTAR_PRODUCTOS
SP_CONTAR_STOCK_CRITICO|CONSULTAR_PRODUCTOS
