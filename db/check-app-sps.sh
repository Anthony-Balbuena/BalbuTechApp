if [ "$missing" -gt 0 ]; then
  echo "Faltantes: $missing de $checked."
  [ "$conn_errors" -gt 0 ] && echo "Incluye $conn_errors sin poder verificar (error de conexion)."
  exit 1
fi
echo "Faltantes: 0 (verificados $checked)."
exit 0
