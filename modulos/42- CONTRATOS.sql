/*
ARCHIVO 42 - CONTRATOS (registro de contratos de empleados)
El modulo de la app ya genera el HTML del contrato; esta tabla deja
constancia de que existe y en que estado esta (activo o finalizado).
- SALARIO es un snapshot: se copia de EMPLEADOS al momento de registrar,
  si despues cambia el salario del empleado el contrato viejo no se toca.
- FECHA_FIN NULL = contrato indefinido.
- Solo un contrato ACTIVO por empleado (lo valida el SP).
- Al despedir se finaliza a mano por ahora (opcion del menu empleados).
*/
CREATE TABLE IF NOT EXISTS CONTRATOS (
    ID_CONTRATO INT NOT NULL AUTO_INCREMENT,
    ID_EMPLEADO INT NOT NULL,
    TIPO ENUM('FIJO', 'INDEFINIDO') NOT NULL,
    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NULL,
    SALARIO DECIMAL(10, 2) NOT NULL,
    RUTA_DOCUMENTO VARCHAR(255) NULL,
    ESTADO ENUM('ACTIVO', 'FINALIZADO') NOT NULL DEFAULT 'ACTIVO',
    FECHA_REGISTRO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_CONTRATO),
    CONSTRAINT FK_CONTRATO_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS (ID_EMPLEADO)
) ENGINE = InnoDB;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_INSERTAR_CONTRATO //
/*
SP_INSERTAR_CONTRATO
Registra un contrato para un empleado.
P_MESES: duracion en meses (solo FIJO; para INDEFINIDO se pasa NULL y
FECHA_FIN queda NULL). FECHA_INICIO es siempre hoy.
SALARIO se copia de EMPLEADOS (snapshot). Frena si el empleado no existe,
esta INACTIVO, o ya tiene un contrato ACTIVO.
*/
CREATE PROCEDURE SP_INSERTAR_CONTRATO(
    IN P_ID_EMPLEADO INT,
    IN P_TIPO VARCHAR(10),
    IN P_MESES INT,
    IN P_RUTA VARCHAR(255)
)
proc_label: BEGIN
    DECLARE v_salario DECIMAL(10, 2);
    DECLARE v_estado VARCHAR(10);
    DECLARE v_nuevo_id INT;

    -- 1. Datos minimos
    IF P_ID_EMPLEADO IS NULL OR P_ID_EMPLEADO <= 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: INGRESE EL ID DEL EMPLEADO.';
    END IF;
    IF P_TIPO IS NULL OR P_TIPO NOT IN ('FIJO', 'INDEFINIDO') THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL TIPO DEBE SER FIJO O INDEFINIDO.';
    END IF;
    IF P_TIPO = 'FIJO' AND (P_MESES IS NULL OR P_MESES < 1) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL CONTRATO FIJO NECESITA UNA DURACION EN MESES MAYOR A CERO.';
    END IF;
    IF P_TIPO = 'INDEFINIDO' THEN
        SET P_MESES = NULL;
    END IF;

    -- 2. El empleado debe existir y estar ACTIVO
    SELECT SALARIO, ESTADO INTO v_salario, v_estado
    FROM EMPLEADOS WHERE ID_EMPLEADO = P_ID_EMPLEADO;
    IF v_salario IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: NO EXISTE UN EMPLEADO CON ESE ID.';
    END IF;
    IF v_estado <> 'ACTIVO' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL EMPLEADO NO ESTA ACTIVO. NO SE LE PUEDE REGISTRAR UN CONTRATO.';
    END IF;

    -- 3. Un solo contrato ACTIVO por empleado
    IF EXISTS (
        SELECT 1 FROM CONTRATOS
        WHERE ID_EMPLEADO = P_ID_EMPLEADO AND ESTADO = 'ACTIVO'
    ) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL EMPLEADO YA TIENE UN CONTRATO ACTIVO. FINALIZELO ANTES DE REGISTRAR OTRO.';
    END IF;

    -- 4. Insertamos (salario snapshot, inicio hoy, fin segun duracion)
    INSERT INTO CONTRATOS (ID_EMPLEADO, TIPO, FECHA_INICIO, FECHA_FIN, SALARIO, RUTA_DOCUMENTO)
    VALUES (
        P_ID_EMPLEADO,
        P_TIPO,
        CURDATE(),
        CASE WHEN P_TIPO = 'FIJO' THEN DATE_ADD(CURDATE(), INTERVAL P_MESES MONTH) ELSE NULL END,
        v_salario,
        P_RUTA
    );
    SET v_nuevo_id = LAST_INSERT_ID();

    SELECT CONCAT('EXITO: CONTRATO #', v_nuevo_id, ' REGISTRADO.') AS MENSAJE;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_FINALIZAR_CONTRATO //
/*
SP_FINALIZAR_CONTRATO
Pasa un contrato de ACTIVO a FINALIZADO (a mano, p.ej. al despedir).
FECHA_FIN: si era NULL (indefinido) se pone hoy; si el fijo vence en el
futuro (finalizacion anticipada) se corta a hoy; si ya vencio se conserva.
*/
CREATE PROCEDURE SP_FINALIZAR_CONTRATO(
    IN P_ID_CONTRATO INT
)
proc_label: BEGIN
    DECLARE v_est_actual VARCHAR(10) DEFAULT NULL;

    IF P_ID_CONTRATO IS NULL OR P_ID_CONTRATO <= 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: INGRESE EL ID DEL CONTRATO.';
    END IF;

    SELECT ESTADO INTO v_est_actual FROM CONTRATOS WHERE ID_CONTRATO = P_ID_CONTRATO;
    IF v_est_actual IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: NO EXISTE UN CONTRATO CON ESE ID.';
    END IF;
    IF v_est_actual = 'FINALIZADO' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL CONTRATO YA ESTA FINALIZADO.';
    END IF;

    UPDATE CONTRATOS
    SET ESTADO = 'FINALIZADO',
        FECHA_FIN = COALESCE(LEAST(FECHA_FIN, CURDATE()), CURDATE())
    WHERE ID_CONTRATO = P_ID_CONTRATO;

    SELECT CONCAT('EXITO: CONTRATO #', P_ID_CONTRATO, ' FINALIZADO.') AS MENSAJE;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_CONTRATOS_POR_EMPLEADO //
/*
SP_CONTRATOS_POR_EMPLEADO
Historial completo de contratos de un empleado (mas reciente primero).
Frena si el empleado no existe.
*/
CREATE PROCEDURE SP_CONTRATOS_POR_EMPLEADO(
    IN P_ID_EMPLEADO INT
)
proc_label: BEGIN
    IF P_ID_EMPLEADO IS NULL OR P_ID_EMPLEADO <= 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: INGRESE EL ID DEL EMPLEADO.';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM EMPLEADOS WHERE ID_EMPLEADO = P_ID_EMPLEADO) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: NO EXISTE UN EMPLEADO CON ESE ID.';
    END IF;

    SELECT
        C.ID_CONTRATO,
        C.TIPO,
        C.FECHA_INICIO,
        C.FECHA_FIN,
        C.SALARIO,
        C.ESTADO,
        C.RUTA_DOCUMENTO
    FROM CONTRATOS C
    WHERE C.ID_EMPLEADO = P_ID_EMPLEADO
    ORDER BY C.ID_CONTRATO DESC;
END //
DELIMITER ;
