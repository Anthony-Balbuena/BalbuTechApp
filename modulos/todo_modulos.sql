CREATE PROCEDURE 11_SP_BLOQUEAR_EDICION_ANTIGUA(
    IN P_ID_EMPLEADO INT,
    IN P_FECHA DATE
)
proc_label: BEGIN
    -- Si la fecha es mayor a 7 días atrás, bloqueamos la edición
