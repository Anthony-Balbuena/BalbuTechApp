--INSERTAR

DELIMITER //
DROP PROCEDURE IF EXISTS 10_SP_INSERTAR_USUARIO ;
CREATE PROCEDURE 10_SP_INSERTAR_USUARIO(
    IN P_ID_EMPLEADO INT,
    IN P_ID_ROL      INT,
    IN P_USUARIO     VARCHAR(50),
    IN P_CONTRASENA  VARCHAR(255)
)
proc_label: BEGIN
    DECLARE v_usuario_limpio VARCHAR(50);
    DECLARE v_nombre_empleado VARCHAR(100);

    -- 1. Obtener el nombre del empleado para validar
    SELECT NOMBRE INTO v_nombre_empleado FROM EMPLEADOS WHERE ID_EMPLEADO = P_ID_EMPLEADO;

    IF v_nombre_empleado IS NULL THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EMPLEADO NO ENCONTRADO.';
        LEAVE proc_label;
    END IF;

    -- 2. Limpieza y formato (Forzamos minúsculas y sin espacios)
    SET v_usuario_limpio = LOWER(REPLACE(TRIM(P_USUARIO), ' ', '.'));

    -- 3. Validar duplicidad
    IF EXISTS (SELECT 1 FROM USUARIOS WHERE USUARIO = v_usuario_limpio) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: ESTE NOMBRE DE USUARIO YA ESTÁ EN USO.';
        LEAVE proc_label;
    END IF;

    -- 4. Inserción
    INSERT INTO USUARIOS (ID_EMPLEADO, ID_ROL, USUARIO, CONTRASENA)
    VALUES (P_ID_EMPLEADO, P_ID_ROL, v_usuario_limpio, v_CONTRASENA);

    SELECT CONCAT('EXITO: USUARIO "', v_usuario_limpio, '" CREADO PARA EL EMPLEADO: ', v_nombre_empleado) AS MENSAJE;
END ;
DELIMITER ;


--ACTUALIZAR
use BALBU_TECH;
DELIMITER //
DROP PROCEDURE IF EXISTS 10_SP_ACTUALIZAR_USUARIO ;
CREATE PROCEDURE 10_SP_ACTUALIZAR_USUARIO(
    IN P_ID_USUARIO   INT,
    IN P_CONTRASENA   VARCHAR(255),
    IN P_USUARIO      VARCHAR(50),
    IN P_ID_ROL       INT,
    IN P_ID_EMPLEADO  INT
)
proc_label: BEGIN
    -- VARIABLES 
    DECLARE v_usuario_limpio    VARCHAR(50);
    DECLARE v_contrasena_limpia VARCHAR(255); 

    -- 1. VALIDAR QUE EL ID EXISTA
    IF NOT EXISTS (SELECT 1 FROM `USUARIOS` WHERE `ID_USUARIO` = P_ID_USUARIO) THEN 
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL USUARIO NO EXISTE.';
        LEAVE proc_label;
    END IF;

    -- 2. VALIDAR USUARIO (Limpieza y Duplicidad)
    IF P_USUARIO IS NOT NULL THEN
        SET v_usuario_limpio = LOWER(TRIM(P_USUARIO)); -- En usuarios mejor usar LOWER
        IF v_usuario_limpio = '' THEN 
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL USUARIO NO PUEDE ESTAR VACÍO.';
            LEAVE proc_label;
        END IF;
        
        -- Validar que el nombre no lo tenga OTRO usuario
        IF EXISTS (SELECT 1 FROM `USUARIOS` WHERE `USUARIO` = v_usuario_limpio AND `ID_USUARIO` <> P_ID_USUARIO) THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: YA HAY OTRO USUARIO CON ESE NOMBRE.';
            LEAVE proc_label;
        END IF;
    END IF;

    -- 3. VALIDAR CONTRASENA 
    IF P_CONTRASENA IS NOT NULL THEN 
        SET v_contrasena_limpia = TRIM(P_CONTRASENA);
        IF v_contrasena_limpia = '' THEN
            SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: LA CLAVE NO PUEDE ESTAR VACÍA.';
            LEAVE proc_label;
        END IF;
    END IF;

    -- 4. VALIDAR FKs
    IF P_ID_ROL IS NOT NULL AND NOT EXISTS (SELECT 1 FROM `ROLES` WHERE `ID_ROL` = P_ID_ROL) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL ROL ESPECIFICADO NO EXISTE.';
        LEAVE proc_label;
    END IF;

    IF P_ID_EMPLEADO IS NOT NULL AND NOT EXISTS (SELECT 1 FROM `EMPLEADOS` WHERE `ID_EMPLEADO` = P_ID_EMPLEADO) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: EL EMPLEADO ESPECIFICADO NO EXISTE.';
        LEAVE proc_label;
    END IF;

    -- 5. ACTUALIZACIÓN DINÁMICA 
    UPDATE `USUARIOS` 
    SET 
        `USUARIO`     = COALESCE(v_usuario_limpio, `USUARIO`),
        `CONTRASENA`  = COALESCE(v_contrasena_limpia, `CONTRASENA`),
        `ID_EMPLEADO` = COALESCE(P_ID_EMPLEADO, `ID_EMPLEADO`),
        `ID_ROL`      = COALESCE(P_ID_ROL, `ID_ROL`)
    WHERE `ID_USUARIO` = P_ID_USUARIO;

    -- 6. MENSAJE DE RETORNO 
    SET @mensaje_final = (SELECT CONCAT('EXITO: EL USUARIO "', 
                                        `USUARIO`, 
                                        '" FUE ACTUALIZADO. (ID_ROL: ', 
                                        `ID_ROL`, ')') 
                          FROM `USUARIOS` WHERE `ID_USUARIO` = P_ID_USUARIO);
                          
    SELECT @mensaje_final AS MENSAJE;                                     

END ;
