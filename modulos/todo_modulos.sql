    INSERT INTO DEVOLUCIONES (ID_DETALLE_VENTA, ID_GARANTIA, ID_EMPLEADO, CANTIDAD, MOTIVO)
    VALUES (P_ID_DETALLE_VENTA, P_ID_GARANTIA, P_ID_EMPLEADO, P_CANTIDAD, P_MOTIVO);

