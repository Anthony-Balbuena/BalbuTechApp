/*
MODULO 57 - AUDITORIA_SISTEMA: SPS Y TRIGGERS

Arregla cuatro cosas del modulo 6 en las bases que ya existen:

  1. Los DROP de los dos SP de consulta no coincidian con sus CREATE
     (se borraba el nombre sin prefijo y se creaba el 6_). Ahora se
     dropean los dos nombres y no quedan versiones viejas vivas.
  2. 6_SP_LISTAR_AUDITORIA_GENERAL usaba DATE(FECHA_HORA), que anula el
     indice IX_AUDITORIA_FECHA. Pasa a un rango sobre la columna y suma
     LIMIT 500 para no tragarse la bitacora entera.
  3. USUARIO_SISTEMA guardaba USER() (el usuario de MySQL, siempre
     balbu_app). Ahora usa @ID_USUARIO_ACTUAL, que la app deja en la
     conexion al iniciar sesion; si no esta, cae a USER().
  4. Faltaba auditar el DELETE de proveedores. Se agrega
     TR_AUDIT_PROVEEDORES_DELETE.

Tambien SP_LIMPIAR_AUDITORIA ahora dice cuantas filas borro.
Es idempotente y no toca datos.
*/

DELIMITER //

-- 1. LISTAR
DROP PROCEDURE IF EXISTS SP_LISTAR_AUDITORIA_GENERAL //
DROP PROCEDURE IF EXISTS 6_SP_LISTAR_AUDITORIA_GENERAL //
CREATE PROCEDURE 6_SP_LISTAR_AUDITORIA_GENERAL(
    IN P_TABLA VARCHAR(50),
    IN P_FECHA_INICIO DATE,
    IN P_FECHA_FIN DATE
)
BEGIN
    SELECT * FROM AUDITORIA_SISTEMA
    WHERE (P_TABLA IS NULL OR P_TABLA = '' OR TABLA_AFECTADA = P_TABLA)
      AND FECHA_HORA >= IFNULL(P_FECHA_INICIO, '1900-01-01')
      AND FECHA_HORA < DATE_ADD(IFNULL(P_FECHA_FIN, CURDATE()), INTERVAL 1 DAY)
    ORDER BY FECHA_HORA DESC
    LIMIT 500;
END //

-- 2. CONSULTAR
DROP PROCEDURE IF EXISTS SP_CONSULTAR_HISTORIAL_REGISTRO //
DROP PROCEDURE IF EXISTS 6_SP_CONSULTAR_HISTORIAL_REGISTRO //
CREATE PROCEDURE 6_SP_CONSULTAR_HISTORIAL_REGISTRO(
    IN P_TABLA VARCHAR(50),
    IN P_ID_REGISTRO INT
)
BEGIN
    SELECT ID_AUDITORIA, ACCION, USUARIO_SISTEMA, FECHA_HORA, VALOR_ANTERIOR, VALOR_NUEVO
    FROM AUDITORIA_SISTEMA
    WHERE TABLA_AFECTADA = P_TABLA
      AND ID_REGISTRO_AFECTADO = P_ID_REGISTRO
    ORDER BY FECHA_HORA DESC;
END //

-- 3. LIMPIAR
DROP PROCEDURE IF EXISTS SP_LIMPIAR_AUDITORIA //
DROP PROCEDURE IF EXISTS 6_SP_LIMPIAR_AUDITORIA //
CREATE PROCEDURE SP_LIMPIAR_AUDITORIA(
    IN P_DIAS_ANTIGUEDAD INT
)
BEGIN
    DECLARE V_BORRADOS INT;

    IF IFNULL(P_DIAS_ANTIGUEDAD, 0) <= 0 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'ERROR: LOS DIAS DEBEN SER MAYORES A CERO.';
    END IF;
    DELETE FROM AUDITORIA_SISTEMA
    WHERE FECHA_HORA < DATE_SUB(NOW(), INTERVAL P_DIAS_ANTIGUEDAD DAY);
    SET V_BORRADOS = ROW_COUNT();

    SELECT CONCAT('LIMPIEZA COMPLETADA: ', V_BORRADOS, ' REGISTROS DE MAS DE ', P_DIAS_ANTIGUEDAD, ' DIAS ELIMINADOS.') AS MENSAJE;
END //

-- 4. TRIGGERS DE PROVEEDORES
DROP TRIGGER IF EXISTS TR_AUDIT_PROVEEDORES_INSERT //
CREATE TRIGGER TR_AUDIT_PROVEEDORES_INSERT
AFTER INSERT ON PROVEEDORES
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_SISTEMA (TABLA_AFECTADA, ID_REGISTRO_AFECTADO, ACCION, USUARIO_SISTEMA, VALOR_NUEVO)
    VALUES ('PROVEEDORES', NEW.ID_PROVEEDOR, 'INSERT',
            IFNULL((SELECT USUARIO FROM USUARIOS WHERE ID_USUARIO = @ID_USUARIO_ACTUAL), USER()),
            CONCAT('Nombre: ', NEW.NOMBRE, ', Tel: ', NEW.TELEFONO, ', Email: ', NEW.EMAIL));
END //

DROP TRIGGER IF EXISTS TR_AUDIT_PROVEEDORES_UPDATE //
CREATE TRIGGER TR_AUDIT_PROVEEDORES_UPDATE
AFTER UPDATE ON PROVEEDORES
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_SISTEMA (TABLA_AFECTADA, ID_REGISTRO_AFECTADO, ACCION, USUARIO_SISTEMA, VALOR_ANTERIOR, VALOR_NUEVO)
    VALUES ('PROVEEDORES', OLD.ID_PROVEEDOR, 'UPDATE',
            IFNULL((SELECT USUARIO FROM USUARIOS WHERE ID_USUARIO = @ID_USUARIO_ACTUAL), USER()),
            CONCAT('Nombre: ', OLD.NOMBRE, ', Tel: ', OLD.TELEFONO, ', Email: ', OLD.EMAIL),
            CONCAT('Nombre: ', NEW.NOMBRE, ', Tel: ', NEW.TELEFONO, ', Email: ', NEW.EMAIL));
END //

DROP TRIGGER IF EXISTS TR_AUDIT_PROVEEDORES_DELETE //
CREATE TRIGGER TR_AUDIT_PROVEEDORES_DELETE
AFTER DELETE ON PROVEEDORES
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_SISTEMA (TABLA_AFECTADA, ID_REGISTRO_AFECTADO, ACCION, USUARIO_SISTEMA, VALOR_ANTERIOR)
    VALUES ('PROVEEDORES', OLD.ID_PROVEEDOR, 'DELETE',
            IFNULL((SELECT USUARIO FROM USUARIOS WHERE ID_USUARIO = @ID_USUARIO_ACTUAL), USER()),
            CONCAT('Nombre: ', OLD.NOMBRE, ', Tel: ', OLD.TELEFONO, ', Email: ', OLD.EMAIL));
END //

DELIMITER ;
