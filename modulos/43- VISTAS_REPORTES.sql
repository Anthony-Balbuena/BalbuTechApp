-- 43- VISTAS_REPORTES.sql
-- (20/10/2026) Vistas que cruzan tablas creadas en modulos posteriores.
--
-- Por que viven aca y no en su modulo original:
-- MariaDB valida las tablas referenciadas al crear una VIEW. Estas 5 leen
-- DETALLE_COMPRA / DEVOLUCION_COMPRA (modulo 22) y DEVOLUCIONES (modulo 26),
-- que se importan despues de los modulos donde estaban definidas (19, 19.5,
-- 23 y 24). En una base existente nunca fallaban porque las tablas ya estaban;
-- en una reconstruccion desde cero el CREATE VIEW fallaba y el import seguia
-- con --force, dejando la base sin estas 5 vistas.
--
-- Este modulo corre al final (despues del 42), cuando ya existen todas las
-- tablas que necesitan. No cambiar el numero sin revisar el orden del import.

/*
VISTA_COMPRA_CON_IVA (11/10/2026)
La compra con su ITBIS: SUBTOTAL (TOTAL) + ITBIS de lineas - ITBIS devuelto
(solo PROCESADA mueve dinero) = TOTAL final (bruto). El TOTAL no se toca para
no romper cobros ni candados.
*/
CREATE OR REPLACE VIEW VISTA_COMPRA_CON_IVA AS
SELECT C.ID_COMPRA, P.NOMBRE AS PROVEEDOR, C.FECHA, C.ESTADO,
       C.TOTAL AS SUBTOTAL,
       ROUND(IFNULL(D.ITBIS_LINEAS, 0) - IFNULL(DV.ITBIS_DEVUELTO, 0), 2) AS ITBIS,
       ROUND(C.TOTAL + IFNULL(D.ITBIS_LINEAS, 0) - IFNULL(DV.ITBIS_DEVUELTO, 0), 2) AS TOTAL_CON_IVA
FROM COMPRAS C
JOIN PROVEEDORES P ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
LEFT JOIN (
    SELECT ID_COMPRA, SUM(MONTO_ITBIS) AS ITBIS_LINEAS
      FROM DETALLE_COMPRA GROUP BY ID_COMPRA
) D ON D.ID_COMPRA = C.ID_COMPRA
LEFT JOIN (
    SELECT DC.ID_COMPRA, SUM(DV.MONTO_ITBIS_DEVUELTO) AS ITBIS_DEVUELTO
      FROM DEVOLUCION_COMPRA DV
      JOIN DETALLE_COMPRA DC ON DC.ID_DETALLE_COMPRA = DV.ID_DETALLE_COMPRA
     WHERE DV.ESTADO = 'PROCESADA'
     GROUP BY DC.ID_COMPRA
) DV ON DV.ID_COMPRA = C.ID_COMPRA;

/*
VISTA_COMPRAS_PENDIENTES_PAGO
Las compras que aun tienen dinero de por medio: cuanto se le paga al
proveedor y cuanto falta por pagar (SALDO a BRUTO, 13/10/2026). Si el saldo
sale negativo es dinero de mas a favor (compra devuelta ya pagada). Excluye
las CANCELADAS: esas nunca se pagaron.
*/
CREATE OR REPLACE VIEW VISTA_COMPRAS_PENDIENTES_PAGO AS
SELECT
    C.ID_COMPRA,
    P.NOMBRE AS PROVEEDOR,
    C.FECHA,
    C.TOTAL,
    IFNULL(PG.PAGADO, 0) AS PAGADO,
    ROUND(C.TOTAL
        + IFNULL((SELECT SUM(DC2.MONTO_ITBIS) FROM DETALLE_COMPRA DC2 WHERE DC2.ID_COMPRA = C.ID_COMPRA), 0)
        - IFNULL((SELECT SUM(DV.MONTO_ITBIS_DEVUELTO) FROM DEVOLUCION_COMPRA DV
                  JOIN DETALLE_COMPRA DC ON DC.ID_DETALLE_COMPRA = DV.ID_DETALLE_COMPRA
                  WHERE DC.ID_COMPRA = C.ID_COMPRA AND DV.ESTADO = 'PROCESADA'), 0)
        - IFNULL(PG.PAGADO, 0), 2) AS SALDO,
    C.ESTADO
FROM COMPRAS C
JOIN PROVEEDORES P ON P.ID_PROVEEDOR = C.ID_PROVEEDOR
LEFT JOIN (
    SELECT ID_COMPRA, SUM(MONTO) AS PAGADO
      FROM PAGOS_COMPRA
     GROUP BY ID_COMPRA
) PG ON PG.ID_COMPRA = C.ID_COMPRA
WHERE C.ESTADO <> 'CANCELADA'
  AND ROUND(C.TOTAL
        + IFNULL((SELECT SUM(DC2.MONTO_ITBIS) FROM DETALLE_COMPRA DC2 WHERE DC2.ID_COMPRA = C.ID_COMPRA), 0)
        - IFNULL((SELECT SUM(DV.MONTO_ITBIS_DEVUELTO) FROM DEVOLUCION_COMPRA DV
                  JOIN DETALLE_COMPRA DC ON DC.ID_DETALLE_COMPRA = DV.ID_DETALLE_COMPRA
                  WHERE DC.ID_COMPRA = C.ID_COMPRA AND DV.ESTADO = 'PROCESADA'), 0)
        - IFNULL(PG.PAGADO, 0), 2) <> 0
ORDER BY C.FECHA DESC;

/*
VISTA_VENTA_CON_IVA (11/10/2026)
La venta con su ITBIS: SUBTOTAL (TOTAL) + ITBIS de lineas - ITBIS reembolsado
(solo APROBADA/REEMBOLSADA mueven dinero) = TOTAL final (bruto). El TOTAL no se
toca para no romper cobros ni candados.
*/
CREATE OR REPLACE VIEW VISTA_VENTA_CON_IVA AS
SELECT V.ID_VENTA, C.NOMBRE AS CLIENTE, V.FECHA, V.ESTADO,
       V.TOTAL AS SUBTOTAL,
       ROUND(IFNULL(D.ITBIS_LINEAS, 0) - IFNULL(DV.ITBIS_DEVUELTO, 0), 2) AS ITBIS,
       ROUND(V.TOTAL + IFNULL(D.ITBIS_LINEAS, 0) - IFNULL(DV.ITBIS_DEVUELTO, 0), 2) AS TOTAL_CON_IVA
FROM VENTAS V
JOIN CLIENTES C ON C.ID_CLIENTE = V.ID_CLIENTE
LEFT JOIN (
    SELECT ID_VENTA, SUM(MONTO_ITBIS) AS ITBIS_LINEAS
      FROM DETALLES_VENTA GROUP BY ID_VENTA
) D ON D.ID_VENTA = V.ID_VENTA
LEFT JOIN (
    SELECT DV2.ID_VENTA, SUM(DV.MONTO_ITBIS_REEMBOLSADO) AS ITBIS_DEVUELTO
      FROM DEVOLUCIONES DV
      JOIN DETALLES_VENTA DV2 ON DV2.ID_DETALLE_VENTA = DV.ID_DETALLE_VENTA
     WHERE DV.ESTADO IN ('APROBADA', 'REEMBOLSADA')
     GROUP BY DV2.ID_VENTA
) DV ON DV.ID_VENTA = V.ID_VENTA;

/*
VISTA_VENTAS_PENDIENTES_PAGO
Cuanto le falta por cobrar cada venta (por BRUTO: SUBTOTAL + ITBIS - ITBIS
devuelto, 11/10/2026). El trigger de pagos no deja que se
pague de mas, asi que el saldo nunca queda negativo. Se excluyen las ventas
CANCELADAS (ya no se les cobra nada) y las DEVUELTAS, ademas de las que ya
estan saldadas (saldo 0).
*/
CREATE OR REPLACE VIEW VISTA_VENTAS_PENDIENTES_PAGO AS
SELECT
    V.ID_VENTA,
    V.ID_CLIENTE,
    V.ESTADO,
    V.TOTAL,
    IFNULL(SUM(P.MONTO), 0) AS PAGADO,
    ROUND(V.TOTAL
        + IFNULL((SELECT SUM(DV2.MONTO_ITBIS) FROM DETALLES_VENTA DV2 WHERE DV2.ID_VENTA = V.ID_VENTA), 0)
        - IFNULL((SELECT SUM(DV.MONTO_ITBIS_REEMBOLSADO) FROM DEVOLUCIONES DV
                  JOIN DETALLES_VENTA DD ON DD.ID_DETALLE_VENTA = DV.ID_DETALLE_VENTA
                  WHERE DD.ID_VENTA = V.ID_VENTA AND DV.ESTADO IN ('APROBADA', 'REEMBOLSADA')), 0)
        - IFNULL(SUM(P.MONTO), 0), 2) AS SALDO
FROM VENTAS V
LEFT JOIN PAGOS P ON P.ID_VENTA = V.ID_VENTA
WHERE V.ESTADO NOT IN ('CANCELADA', 'DEVUELTA')
GROUP BY V.ID_VENTA, V.ID_CLIENTE, V.ESTADO, V.TOTAL
HAVING SALDO <> 0;

/*
VW_REPORTE_VENTAS
Resumen consolidado: UNA fila por venta con el empleado que la atendio,
el cliente, el total, lo efectivamente cobrado (SUM sobre PAGOS) y el
saldo que falta (a BRUTO). Ojo con CANCELADA/DEVUELTA: a esas ya no se les
cobra, el saldo se muestra tal cual (quien solo quiera lo cobrable usa
VISTA_VENTAS_PENDIENTES_PAGO, que las excluye).
*/
CREATE OR REPLACE VIEW VW_REPORTE_VENTAS AS
SELECT
    V.ID_VENTA,
    V.FECHA,
    V.ESTADO,
    E.NOMBRE AS EMPLEADO,
    C.NOMBRE AS CLIENTE,
    V.FACTURA,
    V.TOTAL,
    IFNULL(PG.PAGADO, 0) AS PAGADO,
    ROUND(V.TOTAL
        + IFNULL((SELECT SUM(DV2.MONTO_ITBIS) FROM DETALLES_VENTA DV2 WHERE DV2.ID_VENTA = V.ID_VENTA), 0)
        - IFNULL((SELECT SUM(DV.MONTO_ITBIS_REEMBOLSADO) FROM DEVOLUCIONES DV
                  JOIN DETALLES_VENTA DD ON DD.ID_DETALLE_VENTA = DV.ID_DETALLE_VENTA
                  WHERE DD.ID_VENTA = V.ID_VENTA AND DV.ESTADO IN ('APROBADA', 'REEMBOLSADA')), 0)
        - IFNULL(PG.PAGADO, 0), 2) AS SALDO
FROM VENTAS V
JOIN EMPLEADOS E ON E.ID_EMPLEADO = V.ID_EMPLEADO
JOIN CLIENTES  C ON C.ID_CLIENTE  = V.ID_CLIENTE
LEFT JOIN (SELECT ID_VENTA, SUM(MONTO) AS PAGADO
             FROM PAGOS
            GROUP BY ID_VENTA) PG ON PG.ID_VENTA = V.ID_VENTA;
