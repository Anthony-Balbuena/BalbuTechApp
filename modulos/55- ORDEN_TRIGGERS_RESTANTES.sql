/*
MODULO 55 - ORDEN DE LOS TRIGGERS RESTANTES

Completa lo que arreglo el modulo 54. Recrea con orden explicito los tres
triggers que en la base viva habian quedado creados antes de que sus modulos
declararan el orden:

  DETALLES_VENTA  TR_VALIDAR_STOCK_DETALLE_VENTA
                  FOLLOWS TR_BLOQUEAR_VENTA_FINALIZADA
  EMPLEADOS       TR_AUDITORIA_PERFIL_EMPLEADO
                  FOLLOWS TR_DESACTIVAR_USUARIO_POST_LIQUIDACION
  PRODUCTOS       TR_LOG_CAMBIO_ESTADO_PRODUCTO
                  FOLLOWS TR_AUDITORIA_PRODUCTOS_UPDATE

No cambia ningun cuerpo: son los mismos de los modulos 23, 15 y 18.
Es idempotente y no toca datos ni tablas.
*/

DELIMITER //

DROP TRIGGER IF EXISTS TR_VALIDAR_STOCK_DETALLE_VENTA //

CREATE TRIGGER TR_VALIDAR_STOCK_DETALLE_VENTA
BEFORE INSERT ON DETALLES_VENTA
FOR EACH ROW
FOLLOWS TR_BLOQUEAR_VENTA_FINALIZADA
BEGIN
    DECLARE V_STOCK INT;
    SELECT STOCK_ACTUAL INTO V_STOCK FROM INVENTARIO WHERE ID_PRODUCTO = NEW.ID_PRODUCTO;

    IF V_STOCK IS NULL THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ERROR: EL PRODUCTO NO TIENE REGISTRO EN INVENTARIO.';
    END IF;

    IF V_STOCK < NEW.CANTIDAD THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ERROR: STOCK INSUFICIENTE.';
    END IF;
END //

DROP TRIGGER IF EXISTS TR_AUDITORIA_PERFIL_EMPLEADO //

CREATE TRIGGER TR_AUDITORIA_PERFIL_EMPLEADO
AFTER UPDATE ON EMPLEADOS
FOR EACH ROW
FOLLOWS TR_DESACTIVAR_USUARIO_POST_LIQUIDACION
BEGIN
    IF OLD.SALARIO <> NEW.SALARIO OR
       OLD.CARGO <> NEW.CARGO OR
       OLD.ESTADO <> NEW.ESTADO THEN

        INSERT INTO HISTORIAL_LABORAL_EMPLEADO (
            ID_EMPLEADO,
            CARGO_ANTERIOR, CARGO_NUEVO,
            SALARIO_ANTERIOR, SALARIO_NUEVO,
            ESTADO_ANTERIOR, ESTADO_NUEVO,
            TIPO_CAMBIO,
            OBSERVACION
        )
        VALUES (
            NEW.ID_EMPLEADO,
            OLD.CARGO, NEW.CARGO,
            OLD.SALARIO, NEW.SALARIO,
            OLD.ESTADO, NEW.ESTADO,
            CASE
                WHEN NEW.CARGO <> OLD.CARGO THEN 'PROMOCION'
                WHEN NEW.SALARIO > OLD.SALARIO THEN 'AUMENTO'
                WHEN NEW.ESTADO <> OLD.ESTADO THEN 'CAMBIO_ESTADO'
                ELSE 'AJUSTE'
            END,
            CONCAT('Cambio automático: Cargo(', OLD.CARGO, '->', NEW.CARGO, ') Estado(', OLD.ESTADO, '->', NEW.ESTADO, ')')
        );
    END IF;
END //

DROP TRIGGER IF EXISTS TR_LOG_CAMBIO_ESTADO_PRODUCTO //

CREATE TRIGGER TR_LOG_CAMBIO_ESTADO_PRODUCTO
AFTER UPDATE ON PRODUCTOS
FOR EACH ROW
FOLLOWS TR_AUDITORIA_PRODUCTOS_UPDATE
BEGIN
    IF OLD.ESTADO <> NEW.ESTADO THEN
        INSERT INTO HISTORIAL_ESTADOS_PRODUCTO (
            ID_PRODUCTO,
            ID_EMPLEADO,
            ESTADO,
            ESTADO_ANTERIOR,
            MOTIVO_CAMBIO
        )
        VALUES (
            NEW.ID_PRODUCTO,
            IFNULL(@ID_EMPLEADO_ACTUAL, 1),
            NEW.ESTADO,
            OLD.ESTADO,
            IFNULL(@MOTIVO_CAMBIO, 'Cambio de estado automático')
        );
    END IF;
END //

DELIMITER ;
