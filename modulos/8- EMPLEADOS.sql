        CARGO,
        ESTADO
    FROM EMPLEADOS
    WHERE (
        ID_EMPLEADO = P_TERMINO -- Si es un número exacto
        OR CEDULA LIKE CONCAT('%', P_TERMINO, '%')
        OR NOMBRE LIKE CONCAT('%', P_TERMINO, '%')
        OR CARGO  LIKE CONCAT('%', P_TERMINO, '%')
    )
