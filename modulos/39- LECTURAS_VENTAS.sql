DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTAS_ULTIMAS ;
CREATE PROCEDURE SP_VENTAS_ULTIMAS()
BEGIN
    SELECT ID_VENTA, CLIENTE, FECHA, ESTADO, SUBTOTAL, ITBIS, TOTAL_CON_IVA
      FROM VISTA_VENTA_CON_IVA
     ORDER BY ID_VENTA DESC LIMIT 20;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_ENCABEZADO ;
CREATE PROCEDURE SP_VENTA_ENCABEZADO(IN P_ID_VENTA INT)
BEGIN
