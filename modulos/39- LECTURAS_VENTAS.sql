DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTAS_ULTIMAS ;
CREATE PROCEDURE SP_VENTAS_ULTIMAS()
BEGIN
    SELECT ID_VENTA, CLIENTE, FECHA, ESTADO, SUBTOTAL, ITBIS, TOTAL_CON_IVA
      FROM VISTA_VENTA_CON_IVA
     ORDER BY ID_VENTA DESC LIMIT 20;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_ENCABEZADO ;
CREATE PROCEDURE SP_VENTA_ENCABEZADO(IN P_ID_VENTA INT)
BEGIN
    SELECT ID_VENTA, CLIENTE, FECHA, ESTADO, SUBTOTAL, ITBIS, TOTAL_CON_IVA
      FROM VISTA_VENTA_CON_IVA WHERE ID_VENTA = P_ID_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_LINEAS ;
CREATE PROCEDURE SP_VENTA_LINEAS(IN P_ID_VENTA INT)
BEGIN
    SELECT P.NOMBRE, DV.CANTIDAD, DV.PRECIO_UNITARIO, DV.SUBTOTAL,
           DV.MONTO_ITBIS, (DV.SUBTOTAL + DV.MONTO_ITBIS) AS TOTAL_LINEA
      FROM DETALLES_VENTA DV
      JOIN PRODUCTOS P ON P.ID_PRODUCTO = DV.ID_PRODUCTO
     WHERE DV.ID_VENTA = P_ID_VENTA
     ORDER BY DV.ID_DETALLE_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_ESTADO ;
CREATE PROCEDURE SP_VENTA_ESTADO(IN P_ID_VENTA INT)
BEGIN
    SELECT ESTADO FROM VENTAS WHERE ID_VENTA = P_ID_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_PAGOS_POR_VENTA ;
CREATE PROCEDURE SP_PAGOS_POR_VENTA(IN P_ID_VENTA INT)
BEGIN
    SELECT ID_PAGO, NOMBRE_METODO, MONTO, MONTO_RECIBIDO, NOMBRE_EMPLEADO
      FROM VISTA_RESUMEN_PAGOS WHERE ID_VENTA = P_ID_VENTA ORDER BY ID_PAGO;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_PAGOS_ULTIMOS ;
CREATE PROCEDURE SP_PAGOS_ULTIMOS()
BEGIN
    SELECT ID_PAGO, ID_VENTA, NOMBRE_METODO, MONTO, MONTO_RECIBIDO, NOMBRE_EMPLEADO
      FROM VISTA_RESUMEN_PAGOS ORDER BY ID_PAGO DESC LIMIT 20;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_DETALLES_VENDIDOS_ULTIMOS ;
CREATE PROCEDURE SP_DETALLES_VENDIDOS_ULTIMOS()
BEGIN
    SELECT DV.ID_DETALLE_VENTA, DV.ID_VENTA, P.NOMBRE, DV.CANTIDAD
      FROM DETALLES_VENTA DV
      JOIN PRODUCTOS P ON P.ID_PRODUCTO = DV.ID_PRODUCTO
     ORDER BY DV.ID_DETALLE_VENTA DESC LIMIT 20;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_DEVOLUCION_PENDIENTE_POR_DETALLE ;
CREATE PROCEDURE SP_DEVOLUCION_PENDIENTE_POR_DETALLE(IN P_ID_DETALLE INT)
BEGIN
    SELECT ID_DEVOLUCION FROM DEVOLUCIONES
     WHERE ID_DETALLE_VENTA = P_ID_DETALLE AND ESTADO = 'PENDIENTE'
     ORDER BY ID_DEVOLUCION DESC LIMIT 1;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_GANANCIAS_MENSUAL ;
CREATE PROCEDURE SP_GANANCIAS_MENSUAL()
BEGIN
    SELECT MES, VENTAS, SUBTOTAL, GANANCIA_BRUTA, GANANCIA_DEVUELTA, GANANCIA_NETA
      FROM VW_GANANCIAS_MENSUAL;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_GANANCIAS_LINEAS ;
CREATE PROCEDURE SP_GANANCIAS_LINEAS(IN P_MES VARCHAR(7))
BEGIN
    SELECT ID_VENTA, FECHA, PRODUCTO, CANTIDAD, ITBIS, COSTO_TOTAL, TOTAL_LINEA,
           GANANCIA, GANANCIA_NETA
      FROM VW_GANANCIAS
     WHERE (P_MES IS NULL OR P_MES = '' OR DATE_FORMAT(FECHA, '%Y-%m') = P_MES)
     ORDER BY ID_VENTA DESC LIMIT 30;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_COMPRAS_ULTIMAS ;
CREATE PROCEDURE SP_COMPRAS_ULTIMAS()
BEGIN
    SELECT ID_COMPRA, PROVEEDOR, FECHA, ESTADO, SUBTOTAL, ITBIS, TOTAL_CON_IVA
      FROM VISTA_COMPRA_CON_IVA
     ORDER BY ID_COMPRA DESC LIMIT 20;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_COMPRA_ENCABEZADO ;
CREATE PROCEDURE SP_COMPRA_ENCABEZADO(IN P_ID_COMPRA INT)
