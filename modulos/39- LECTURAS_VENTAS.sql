      FROM VISTA_VENTA_CON_IVA WHERE ID_VENTA = P_ID_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_LINEAS ;
CREATE PROCEDURE SP_VENTA_LINEAS(IN P_ID_VENTA INT)
BEGIN
    SELECT P.NOMBRE, DV.CANTIDAD, DV.PRECIO_UNITARIO, DV.PORCENTAJE_DESCUENTO, DV.SUBTOTAL,
           DV.MONTO_ITBIS, (DV.SUBTOTAL + DV.MONTO_ITBIS) AS TOTAL_LINEA
      FROM DETALLES_VENTA DV
      JOIN PRODUCTOS P ON P.ID_PRODUCTO = DV.ID_PRODUCTO
     WHERE DV.ID_VENTA = P_ID_VENTA
     ORDER BY DV.ID_DETALLE_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTA_ESTADO ;
CREATE PROCEDURE SP_VENTA_ESTADO(IN P_ID_VENTA INT)
BEGIN
    SELECT ESTADO FROM VENTAS WHERE ID_VENTA = P_ID_VENTA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_PAGOS_POR_VENTA ;
CREATE PROCEDURE SP_PAGOS_POR_VENTA(IN P_ID_VENTA INT)
BEGIN
