    IN P_FECHA_INICIO DATE,
    IN P_FECHA_FIN    DATE,
    IN P_PAGINA       INT,
    IN P_POR_PAGINA   INT
)
proc_label: BEGIN
    DECLARE v_offset INT DEFAULT 0;

    IF P_FECHA_INICIO > P_FECHA_FIN THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ERROR: LA FECHA INICIAL NO PUEDE SER MAYOR A LA FINAL.';
    END IF;
