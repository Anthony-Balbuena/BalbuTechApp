      FROM VISTA_COMPRA_CON_IVA WHERE ID_COMPRA = P_ID_COMPRA;
END //
DELIMITER ;

DELIMITER //
DROP PROCEDURE IF EXISTS SP_COMPRA_LINEAS ;
CREATE PROCEDURE SP_COMPRA_LINEAS(IN P_ID_COMPRA INT)
BEGIN
