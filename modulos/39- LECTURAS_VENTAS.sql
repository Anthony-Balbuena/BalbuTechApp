DELIMITER //
DROP PROCEDURE IF EXISTS SP_VENTAS_PENDIENTES ;
CREATE PROCEDURE SP_VENTAS_PENDIENTES()
BEGIN
    SELECT ID_VENTA, ID_CLIENTE, ESTADO, TOTAL, PAGADO, SALDO
      FROM VISTA_VENTAS_PENDIENTES_PAGO ORDER BY ID_VENTA DESC LIMIT 20;
END //
DELIMITER ;
