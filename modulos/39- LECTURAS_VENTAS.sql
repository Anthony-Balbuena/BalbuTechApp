-- 3.b COMPRAS PAGINADAS (08/11/2026)
-- ================================================================
-- La app ya no lista "las ultimas 20" a secas: pide pagina + total para
-- mostrar de 10 en 10 y poder llegar a una compra vieja. Mismo permiso que
-- sus hermanas (COMPRAS_VER): en la matriz, todo rol con COMPRAS_PAGAR,
-- COMPRAS_CANCELAR o COMPRAS_DEVOLVER tambien tiene COMPRAS_VER.
DELIMITER //
/*
SP_COMPRAS_ULTIMAS_PAGINADO
Una pagina del listado de compras, de la mas nueva a la mas vieja.
*/
DROP PROCEDURE IF EXISTS SP_COMPRAS_ULTIMAS_PAGINADO ;
CREATE PROCEDURE SP_COMPRAS_ULTIMAS_PAGINADO(
    IN P_PAGINA     INT,
    IN P_POR_PAGINA INT
)
BEGIN
    DECLARE v_offset INT DEFAULT 0;

    IF P_PAGINA IS NULL OR P_PAGINA < 1 THEN
        SET P_PAGINA = 1;
    END IF;
    IF P_POR_PAGINA IS NULL OR P_POR_PAGINA < 1 THEN
        SET P_POR_PAGINA = 10;
    END IF;
    SET v_offset = (P_PAGINA - 1) * P_POR_PAGINA;

    SELECT ID_COMPRA, PROVEEDOR, FECHA, ESTADO, SUBTOTAL, ITBIS, TOTAL_CON_IVA
      FROM VISTA_COMPRA_CON_IVA
     ORDER BY ID_COMPRA DESC
     LIMIT P_POR_PAGINA OFFSET v_offset;
END //
DELIMITER ;

DELIMITER //
/*
SP_CONTAR_COMPRAS
Cuantas compras hay en total, para armar "Pagina 1 de N".
*/
DROP PROCEDURE IF EXISTS SP_CONTAR_COMPRAS ;
CREATE PROCEDURE SP_CONTAR_COMPRAS()
BEGIN
    SELECT COUNT(*) AS TOTAL FROM COMPRAS;
END //
